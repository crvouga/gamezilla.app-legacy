export type Iso3166Alpha2Code = keyof typeof ISO_3166_ALPHA_2_MAPPINGS;
const all = Object.keys(ISO_3166_ALPHA_2_MAPPINGS) as Iso3166Alpha2Code[];
const toName = (code: Iso3166Alpha2Code): string => {
    return ISO_3166_ALPHA_2_MAPPINGS[code];
};
const _all = new Set<string>(all);
const is = (code: unknown): code is Iso3166Alpha2Code => {
    return typeof code === "string" && _all.has(code);
};
const of = (code: Iso3166Alpha2Code): Iso3166Alpha2Code => code;
// source: https://github.com/srcagency/country-to-emoji-flag
const toEmoji = (country: Iso3166Alpha2Code): string | undefined => {
    const offset = 127397;
    const A = 65;
    const Z = 90;
    const f = country.codePointAt(0);
    const s = country.codePointAt(1);
    if (!f) {
        return undefined;
    }
    if (!s) {
        return undefined;
    }
    if (country.length !== 2 || f > Z || f < A || s > Z || s < A) {
        return undefined;
    }
    return String.fromCodePoint(f + offset) + String.fromCodePoint(s + offset);
};
const toNameWithEmoji = (code: Iso3166Alpha2Code): string => {
    const emoji = toEmoji(code);
    if (emoji) {
        return `${emoji} ${toName(code)}`;
    }
    return toName(code);
};
const getNavigatorCountry = (): Iso3166Alpha2Code | undefined => {
    const locale: unknown = navigator.language;
    if (typeof locale !== "string") {
        return undefined;
    }
    const countryCode = locale.split("-")[1];
    if (countryCode && Iso3166Alpha2Code.is(countryCode.toUpperCase())) {
        return countryCode.toUpperCase() as Iso3166Alpha2Code;
    }
    return undefined;
};
export const Iso3166Alpha2Code = {
    of,
    toEmoji,
    toName,
    is,
    toNameWithEmoji,
    getNavigatorCountry,
    all,
};
