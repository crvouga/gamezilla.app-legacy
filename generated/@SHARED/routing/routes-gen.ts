const DIR_PATH = path.join(__dirname, "..", "..");
const OUTPUT_DIR = path.join(__dirname, "generated");
const TARGET_FILE_SUFFIX = ".routes.ts";
const DISCLAIMER = `// This file is generated by ${path.basename(__filename)} Do not edit it manually.`;
//
//
//
//
//
//
async function generateRouteTypeFile(files: string[]) {
    const imports: string[] = [];
    const typeRefs: string[] = [];
    const parsers: string[] = [];
    for (const [index, file] of enumerate(files)) {
        const importPath = path
            .relative(path.dirname(__dirname), file)
            .replace(/\\/g, "/");
        imports.push(`import { Route as Route${index}, toRoute as toRoute${index} } from "../../${importPath.replace(".ts", "")}";`);
        typeRefs.push(`Route${index}`);
        parsers.push(`toRoute${index}`);
    }
    const content = `${DISCLAIMER}
${imports.join("\n")}

export type Route = ${typeRefs.join(" | ")};

export const toRoute = (route: unknown) => {
  for (const parser of [${parsers.join(", ")}]) {
    const parsed = parser(route)
    if (parsed !== null) {
      return parsed
    }
  }
  return null
}
`;
    await fs.writeFile(path.join(OUTPUT_DIR, "routes.ts"), content);
}
async function runPrettierOnDirectory(directoryPath: string) {
    return new Promise((resolve, reject) => {
        const command = `npx prettier --loglevel silent --write "${path.join(directoryPath, "**/*.ts")}"`;
        exec(command, (error, stdout, stderr) => {
            if (error) {
                console.error("Error running Prettier:", stderr);
                reject(error);
                return;
            }
            console.log("Formatted generated files with Prettier");
            resolve(stdout);
        });
    });
}
async function main() {
    const files = await scanFiles({
        dir: DIR_PATH,
        targetFileSuffix: TARGET_FILE_SUFFIX,
    });
    await makeDirIfNotExists(OUTPUT_DIR);
    await generateRouteTypeFile(files);
    await runPrettierOnDirectory(OUTPUT_DIR);
}
main().catch(console.error);
