async function makeDirIfNotExists(dirPath: string) {
    const doesExist = await fs
        .access(dirPath)
        .then(() => true)
        .catch(() => false);
    if (!doesExist) {
        await fs.mkdir(dirPath, { recursive: true });
    }
}
function enumerate<T>(iterable: Iterable<T>): Iterable<[
    number,
    T
]> {
    let i = 0;
    return {
        *[Symbol.iterator]() {
            for (const item of iterable) {
                yield [i, item];
                i++;
            }
        },
    };
}
async function scanFiles(input: {
    dir: string;
    targetFileSuffix: string;
}): Promise<string[]> {
    const files: string[] = [];
    const filesAndDirectories = await fs.readdir(input.dir, {
        withFileTypes: true,
    });
    for (const file of filesAndDirectories) {
        const res = path.resolve(input.dir, file.name);
        if (file.isDirectory()) {
            const children = await scanFiles({
                dir: res,
                targetFileSuffix: input.targetFileSuffix,
            });
            files.push(...children);
            continue;
        }
        if (file.name.endsWith(input.targetFileSuffix)) {
            files.push(res);
            continue;
        }
    }
    return files;
}
