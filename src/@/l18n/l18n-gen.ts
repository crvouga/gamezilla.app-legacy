async function generateTextTypeFile(files: string[]) {
  const imports: string[] = []
  const typeRefs: string[] = []

  for (const [index, file] of enumerate(files)) {
    const importPath = path.relative(dirname, file).replace(/\\/g, '/')
    imports.push(`import type { Text as Text${index} } from "../${importPath.replace('.ts', '')}";`)
    typeRefs.push(`Text${index}`)
  }

  const content = `${DISCLAIMER}
${imports.join('\n')}

export type Text = ${typeRefs.join(' & ')};
`

  await fs.writeFile(path.join(OUTPUT_DIR, 'text.ts'), content)
}

async function generateLanguageFiles(files: string[]) {
  const translationsAll: { [key in LanguageCodeISO_639_1]: { [key: string]: string | ((...args: any[]) => string) } } =
    {
      ar: {},
      de: {},
      en: {},
      es: {},
      fr: {},
      hi: {},
      it: {},
      ja: {},
      ko: {},
      pt: {},
      ru: {},
      zh: {},
    }

  for (const file of files) {
    try {
      let relativePath = path.relative(dirname, file)

      relativePath = relativePath.split(path.sep).join('/')

      if (!relativePath.startsWith('.') && !relativePath.startsWith('/')) {
        relativePath = `./${relativePath}`
      }

      const translationsModule = await import(relativePath)

      const translations = translationsModule.translations

      if (!translations) {
        throw new Error(`The file "${file}" does not export a "translations" object.`)
      }

      // New structure: translations[textId][langCode] = value
      // Iterate over text IDs (top-level keys)
      for (const textId in translations) {
        const textTranslations = translations[textId]
        if (textTranslations && typeof textTranslations === 'object') {
          // For each language, add this text ID's translation
          for (const code of LanguageCodeISO_639_1.ALL) {
            if (textTranslations[code] !== undefined) {
              translationsAll[code][textId] = textTranslations[code]
            }
          }
        }
      }
    } catch (error) {
      console.error(`Error processing file "${file}":`, error)

      continue
    }
  }

  try {
    const exists = await fs
      .stat(OUTPUT_TRANSLATIONS_DIR)
      .then(() => true)
      .catch(() => false)
    if (!exists) {
      await fs.mkdir(OUTPUT_TRANSLATIONS_DIR, { recursive: true })
      console.log(`Created output directory: ${OUTPUT_TRANSLATIONS_DIR}`)
    } else {
      console.log(`Output directory already exists: ${OUTPUT_TRANSLATIONS_DIR}`)
    }
  } catch (error) {
    console.error(`Error ensuring output directory exists:`, error)
    throw error
  }

  await Promise.all(
    LanguageCodeISO_639_1.ALL.map(async (code) => {
      const translationsForLanguage = translationsAll[code] ?? {}
      const translationsForLanguageString = serialize(translationsForLanguage)

      const content = `${DISCLAIMER}
import type { Text } from '../text'

export const translations: Text = ${translationsForLanguageString}
`

      const outputPath = path.join(OUTPUT_TRANSLATIONS_DIR, `${code}.ts`)
      try {
        await fs.writeFile(outputPath, content, 'utf-8')
      } catch (error) {
        console.error(`Error writing translation file "${outputPath}":`, error)
      }
    }),
  )

  console.log(`\nGenerated language-specific translation files in: ${OUTPUT_TRANSLATIONS_DIR}`)
}

async function generateIndexFile() {
  const content = `${DISCLAIMER}
import type { LanguageCodeISO_639_1 } from '../lang-code-iso-639-1';  
import { createTranslator } from '../translations';
${LanguageCodeISO_639_1.ALL.map((code) => `import * as ${code} from './translations/${code}'`).join('\n')}

export const translations = {
  ${LanguageCodeISO_639_1.ALL.map((code) => `${code}: ${code}.translations`).join(',\n')}
} as const;

export const Translator = (languageCode: LanguageCodeISO_639_1) => {
  return createTranslator(translations[languageCode])
}

export type Translator = ReturnType<typeof Translator>;
`
  await fs.writeFile(path.join(OUTPUT_DIR, 'index.ts'), content)
  console.log(`Generated index file in: ${OUTPUT_DIR}`)
}

async function runPrettierOnDirectory(directoryPath: string) {
  return new Promise((resolve, reject) => {
    const command = `npx prettier --loglevel silent --write "${path.join(directoryPath, '**/*.ts')}"`

    exec(command, (error, stdout, stderr) => {
      if (error) {
        console.error('Error running Prettier:', stderr)
        reject(error)
        return
      }
      console.log('Formatted generated files with Prettier')
      resolve(stdout)
    })
  })
}

async function main() {
  const files = await scanFiles({
    dir: DIR_PATH,
    targetFileSuffix: TARGET_FILE_SUFFIX,
  })
  await generateLanguageFiles(files)
  await generateTextTypeFile(files)
  await generateIndexFile()
  await runPrettierOnDirectory(OUTPUT_DIR)
}

main().catch(console.error)

