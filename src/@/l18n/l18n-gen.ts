const dirname = path.dirname(fileURLToPath(import.meta.url))
const DIR_PATH = path.join(dirname, '..', '..')
const OUTPUT_DIR = path.join(dirname, 'generated')
const OUTPUT_TRANSLATIONS_DIR = path.join(OUTPUT_DIR, 'translations')
const TARGET_FILE_SUFFIX = '$l18n.ts'

const DISCLAIMER = `// This file is generated by ${path.basename(fileURLToPath(import.meta.url))} Do not edit it manually.`

