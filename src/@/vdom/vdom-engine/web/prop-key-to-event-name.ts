export const propKeyToEventName = (propKey: string): string => {
  switch (propKey) {
    case 'onClick':
      return 'click'
    case 'onPointerDown':
      return 'pointerdown'
    case 'onPointerUp':
      return 'pointerup'
    case 'onPointerCancel':
      return 'pointercancel'
    case 'onPointerMove':
      return 'pointermove'
    case 'onPointerEnter':
      return 'pointerenter'
    case 'onPointerLeave':
      return 'pointerleave'
    case 'onPointerOver':
      return 'pointerover'
    case 'onPointerOut':
      return 'pointerout'
    case 'onInput':
      return 'input'
    case 'onChange':
      return 'change'
    case 'onFocus':
      return 'focus'
    case 'onBlur':
      return 'blur'
    case 'onKeyDown':
      return 'keydown'
    case 'onKeyUp':
      return 'keyup'
    case 'onKeyPress':
      return 'keypress'
    case 'onSubmit':
      return 'submit'
    case 'onDragStart':
      return 'dragstart'
    case 'onDragEnd':
      return 'dragend'
    case 'onDragOver':
      return 'dragover'
    case 'onDragEnter':
      return 'dragenter'
    case 'onDragLeave':
      return 'dragleave'
    case 'onDrop':
      return 'drop'
    case 'onScroll':
      return 'scroll'
    case 'onWheel':
      return 'wheel'
    case 'onCopy':
      return 'copy'
    case 'onCut':
      return 'cut'
    case 'onPaste':
      return 'paste'
    case 'onSelect':
      return 'select'
    case 'onSelectAll':
      return 'selectall'
    case 'onTouchStart':
      return 'touchstart'
    case 'onTouchMove':
      return 'touchmove'
    case 'onTouchEnd':
      return 'touchend'
    case 'onTouchCancel':
      return 'touchcancel'
    default:
      return propKey.slice(2).toLowerCase()
  }
}
